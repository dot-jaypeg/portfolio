import type { ImageGridLayout } from '../components/ImageGrid'

export interface ProjectImage {
  // Omit `src` (and width/height) to render a dashed placeholder box
  // instead -- for a chapter whose real asset hasn't been supplied
  // yet. `alt` doubles as that box's own label in that case.
  src?: string
  // Set instead of `src` to render a <video> in this slot. `videoMode`
  // 'loop' autoplays muted/looped with no controls (ambient UI or
  // environment footage); 'autoplay' plays once scrolled into view,
  // pauses once scrolled out, starting muted but keeping controls so
  // a visitor can unmute; the default, 'controls', is a plain
  // user-initiated player with `poster` as its thumbnail.
  video?: string
  videoMode?: 'controls' | 'loop' | 'autoplay'
  // `videoMode: 'autoplay'` only -- what a click on the video itself
  // does, besides whatever its native `controls` bar already handles
  // on its own. Defaults to 'unmute' (the click toggles mute in
  // place). 'fullscreen' opens the browser's native fullscreen player
  // instead, for a video substantial enough (a full short, not a
  // quick ad loop) to want its own real play/pause/volume/scrub bar
  // rather than inline, below-the-fold controls.
  clickAction?: 'unmute' | 'fullscreen'
  poster?: string
  alt: string
  width?: number
  height?: number
  caption?: string
  // `cluster` layout only -- how wide this image renders relative to
  // the others in the same free-wrapping group. Defaults to 'md'.
  size?: 'sm' | 'md' | 'lg' | 'xl'
  // `cluster`/`Figure` only -- a fixed, static tilt in degrees (not
  // the hover-only tilt `interactive` gives a cluster). For a sticker/
  // product cutout posed at a deliberate angle rather than dead level.
  rotate?: number
  // Defaults to 'cover' (crops to fill its box) everywhere. 'contain'
  // letterboxes instead -- for a source whose own aspect ratio is too
  // different from its box's (e.g. a landscape product shot sitting in
  // a `full-page-two-up` pair's tall column) for 'cover' to show the
  // whole thing without cropping into the actual subject.
  fit?: 'cover' | 'contain'
  // `phone-row` only -- the account name to show in a drawn-on-top
  // Instagram Story UI (progress segment, account row, a reply bar
  // with heart/send icons), for a flat graphic that was never
  // actually screenshotted inside the app, so it reads as a story the
  // way a real screenshot (A7X's) already does on its own. Omit for
  // no overlay.
  storyOverlay?: string
}

// One image block: a layout plus the images it renders. A chapter's
// primary block is its own `layout`/`images`/`tall`; `moreImages` adds
// further blocks in sequence below it, for a chapter that needs more
// than one distinct grouping (e.g. a run of full-page product shots).
export interface ProjectImageBlock {
  layout: ImageGridLayout
  images: ProjectImage[]
  // `full-page` only -- use a taller-than-viewport box, for a square
  // or portrait source a plain viewport-height crop cuts too hard.
  tall?: boolean
  // Pill link buttons (same style as ProjectHero's "Visit Site")
  // right below THIS block specifically -- the chapter's own primary
  // block or any one `moreImages` entry can carry its own, so a link
  // can sit next to the particular image/mockup it's actually about
  // instead of always trailing the whole chapter.
  links?: { label: string; href: string }[]
  // `phone-row` only -- stacks `links` vertically and sits that stack
  // beside the phone mockup(s) in the same row, instead of the
  // default horizontal row of pills underneath. For a single phone
  // that otherwise leaves the rest of the row empty, balancing it
  // against a column of buttons instead.
  linksInline?: boolean
  // A single small note centered below this whole block, not any one
  // image in it -- e.g. "Click to unmute" under a pair of autoplay
  // videos, where the note is about the pair as a unit rather than
  // each video individually.
  blockCaption?: string
}

export interface ProjectChapter extends ProjectImageBlock {
  // Omit for a chapter meant to read as pure imagery with no eyebrow
  // label above its copy.
  label?: string
  // A single paragraph, or several -- rendered as separate <p>s, with
  // the label (if any) only ever sitting above the first. Omit
  // alongside `label` for a chapter that's pure imagery, no copy at all.
  text?: string | string[]
  moreImages?: ProjectImageBlock[]
  // False drops ImageGrid's bg-cream/5 card backdrop for this
  // chapter's images -- for transparent-background cutouts (sketches,
  // sticker renders) where that backdrop would show as an unwanted
  // grey box around the art. Defaults to true.
  imagesOnCard?: boolean
  // Closed by default -- the label becomes a toggle button, and `text`
  // renders small (a notch above the label itself) in a dropdown
  // instead of the standard big editorial paragraph. Requires `label`.
  collapsible?: boolean
  // Renders a page-flip viewer (BrandGuideViewer) below this
  // chapter's images -- `pageCount` pre-rendered page JPGs are
  // expected at `${basePath}/page-01.jpg` etc. in /public (see
  // scripts used to generate public/brand-guides/<slug>/), with
  // `pdfHref` offering the original file as a direct download.
  brandGuide?: { title: string; pageCount: number; basePath: string; pdfHref: string }
  // Renders a live, clickable Figma prototype embed (in a phone-shaped
  // frame) below this chapter's images -- for a prototype a visitor
  // can actually click through themselves instead of only a static
  // screenshot of it.
  figmaEmbed?: { url: string; title: string }
}

export interface ProjectLinks {
  site?: string
  featuredOn?: { label: string; href: string }[]
}

export interface ProjectDetailData {
  // Rendered as `{heroLead} **{heroBold ?? client}**{heroTagline}` --
  // the client name is bolded inline, per the brief's "Brand identity
  // for [Client], a [one-line description]" hero pattern. A couple of
  // CASE_STUDIES `client` values are placeholders ("Academic") rather
  // than a real named entity, which reads oddly bolded into a sentence
  // as though it were a company -- `heroBold` lets those override what
  // actually gets bolded without changing the underlying client data.
  heroLead: string
  heroBold?: string
  heroTagline: string
  // Overrides the hero image's CSS object-position independently of
  // CASE_STUDIES' own `imagePosition` -- that field also drives the
  // homepage WorkPanel crop, so reusing it here would recrop that too.
  // Defaults to `project.imagePosition ?? 'center'` when unset.
  heroImagePosition?: string
  // Overrides the hero's parallax wrapper oversize (default 15, i.e.
  // the wrapper spans -15%/130% of the container for scroll slack).
  // That oversize offset itself eats into the image's own top edge --
  // at the default 15, roughly the top 6% of a cover-fit image is
  // clipped above the visible viewport before `heroImagePosition` is
  // even applied, regardless of position. A photo with real content
  // (a wordmark, a face) sitting in that exact top sliver needs this
  // brought down to stay in frame.
  heroParallaxSlack?: number
  // Switches the mobile hero from `object-cover` to `object-contain`
  // (letterboxed against the page's own ink background instead of
  // cropped) -- for a wide landscape source with real content spread
  // across its FULL width (e.g. a wordmark on one side, a character on
  // the other), no single `heroImagePosition` value can keep both in
  // frame once the hero box itself becomes mobile's narrow portrait
  // shape rather than desktop's wide one: confirmed directly on
  // Resonance, every position tried either cut off the wordmark's own
  // leading or trailing letters. Desktop is unaffected -- its box is
  // close enough to the source's own ratio that `cover` barely crops
  // at all there.
  heroMobileFit?: 'cover' | 'contain'
  tags: string[]
  // A second paragraph is rare -- most projects' intro is one line.
  // NSU's is written as two: a short overview sentence, then a longer
  // one on NSU itself and the role, which read as one run-on mass
  // when forced into a single paragraph.
  intro: string | string[]
  // An optional small mark (a logo, a wordmark) rendered centered
  // between the intro and the first chapter.
  brandMark?: { src: string; alt: string }
  // An optional full-page (parallaxing) lead photo directly under the
  // intro paragraphs, above `brandMark`/the first chapter -- for a
  // single establishing shot that belongs to the overview itself
  // rather than to any one chapter below it.
  introImage?: ProjectImage
  links?: ProjectLinks
  // Optional concrete number/credit -- omitted everywhere for now since
  // none of these are verified yet (see the per-project ask list this
  // was shipped with).
  proofPoint?: string
  chapters: ProjectChapter[]
}

